-- =====================================================
-- Inventory Tracker database
-- Paste this whole file into the Supabase SQL Editor and press Run.
-- It is safe to run again after an update: it keeps existing data.
--
-- How access works:
--   profiles   says which accounts exist and whether they are full or limited.
--              Nobody can change it from the app, only from the Supabase dashboard.
--   products   any account in profiles can read it.
--   movements  only full accounts can read it.
--   Writing    no account can write to a table directly. Every change goes
--              through a function below, and each one checks the access first.
-- A login with no row in profiles can read and do nothing.
-- =====================================================

-- The shop's time zone, used to decide what date and time a record belongs to.
create or replace function public.shop_time()
returns timestamp
language sql stable
set search_path = ''
as $$ select now() at time zone 'Asia/Shanghai' $$;

-- ---------- tables ----------

create table if not exists public.profiles (
  user_id  uuid primary key references auth.users (id) on delete cascade,
  username text not null unique,
  name     text not null,
  access   text not null check (access in ('full', 'limited'))
);

create table if not exists public.products (
  id        bigint generated by default as identity primary key,
  name      text not null check (length(name) between 1 and 200),
  kind      text not null check (kind in ('material', 'product')),
  unit      text not null check (length(unit) between 1 and 50),
  stock     numeric not null default 0,
  min_stock numeric not null default 0
);

-- Not linked to products, because history stays after a product is deleted.
create table if not exists public.movements (
  id           bigint generated by default as identity primary key,
  move_date    date not null,
  move_time    text not null default '',
  product_id   bigint not null,
  product_name text not null,
  type         text not null check (type in ('IN', 'OUT', 'ADJUST')),
  qty          numeric not null check (qty >= 0),
  delta        numeric not null,
  note         text not null default '',
  stock_after  numeric
);

-- Prices change from sale to sale, so they are saved on each record:
-- unit_price is the selling price of an OUT, unit_cost is the cost of an IN.
-- contact is the customer of an OUT, or the supplier of an IN.
alter table public.movements add column if not exists unit_price numeric check (unit_price >= 0);
alter table public.movements add column if not exists unit_cost numeric check (unit_cost >= 0);
alter table public.movements add column if not exists contact text not null default '';

-- Nothing is deleted from the history. Undoing a record adds an UNDO row that
-- points at it through undoes_id, and each record can only be undone once.
alter table public.movements add column if not exists undoes_id bigint unique references public.movements (id);
alter table public.movements drop constraint if exists movements_type_check;
alter table public.movements add constraint movements_type_check
  check (type in ('IN', 'OUT', 'ADJUST', 'UNDO'));

-- The names offered in the Customer and Supplier boxes on the Record page
create table if not exists public.contacts (
  id   bigint generated by default as identity primary key,
  kind text not null check (kind in ('customer', 'supplier')),
  name text not null check (length(name) between 1 and 200)
);
create unique index if not exists contacts_kind_name on public.contacts (kind, lower(name));

-- Shared settings. There is only ever one row.
create table if not exists public.app_settings (
  id              integer primary key default 1 check (id = 1),
  order_now_days  integer not null default 14,
  order_soon_days integer not null default 21
);
insert into public.app_settings (id) values (1) on conflict (id) do nothing;

-- ---------- who is asking ----------

create or replace function public.current_access()
returns text
language sql stable security definer
set search_path = ''
as $$ select access from public.profiles where user_id = auth.uid() $$;

create or replace function public.require_access(allowed text[])
returns void
language plpgsql stable security definer
set search_path = ''
as $$
begin
  if public.current_access() is null or not public.current_access() = any (allowed) then
    raise exception 'Your account is not allowed to do this.' using errcode = '42501';
  end if;
end;
$$;

-- ---------- table rules ----------

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.movements enable row level security;
alter table public.contacts enable row level security;
alter table public.app_settings enable row level security;

drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "accounts read products" on public.products;
create policy "accounts read products" on public.products
  for select to authenticated
  using (public.current_access() in ('full', 'limited'));

drop policy if exists "full accounts read movements" on public.movements;
create policy "full accounts read movements" on public.movements
  for select to authenticated
  using (public.current_access() = 'full');

drop policy if exists "accounts read contacts" on public.contacts;
create policy "accounts read contacts" on public.contacts
  for select to authenticated
  using (public.current_access() in ('full', 'limited'));

drop policy if exists "full accounts read settings" on public.app_settings;
create policy "full accounts read settings" on public.app_settings
  for select to authenticated
  using (public.current_access() = 'full');

revoke all on public.profiles, public.products, public.movements, public.contacts, public.app_settings
  from public, anon, authenticated;
grant select on public.profiles, public.products, public.movements, public.contacts, public.app_settings
  to authenticated;

-- ---------- reading ----------

-- Today's IN and OUT totals for the Home page. Limited accounts cannot read
-- movements, so this gives them the two totals and nothing else.
create or replace function public.today_totals()
returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  perform public.require_access(array['full', 'limited']);
  select jsonb_build_object(
    'in',  coalesce(sum(qty) filter (where type = 'IN'), 0),
    'out', coalesce(sum(qty) filter (where type = 'OUT'), 0)
  ) into result
  from public.movements as m
  where m.move_date = public.shop_time()::date
    and not exists (select from public.movements as u where u.undoes_id = m.id);
  return result;
end;
$$;

-- ---------- writing ----------

-- Record stock IN or OUT for many products at once. All lines are saved
-- together, or none are if one fails.
-- p_lines looks like [{"product_id": 1, "qty": 5, "price": 120}, ...]
-- price is optional: the selling price for OUT, the cost for IN.
-- p_contact is the customer for OUT or the supplier for IN, also optional.
drop function if exists public.record_cart(text, jsonb, text);
create or replace function public.record_cart(
  p_type text, p_lines jsonb, p_note text default '', p_contact text default ''
)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  line record;
  item public.products%rowtype;
  change numeric;
  now_here timestamp := public.shop_time();
  who text := left(trim(coalesce(p_contact, '')), 200);
begin
  perform public.require_access(array['full', 'limited']);
  if p_type not in ('IN', 'OUT') then
    raise exception 'Unknown record type.';
  end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Add at least one product.';
  end if;

  -- Same order every time, so two devices saving at once cannot block each other
  for line in
    select (l ->> 'product_id')::bigint as product_id, (l ->> 'price')::numeric as price,
           sum((l ->> 'qty')::numeric) as qty
    from jsonb_array_elements(p_lines) as l
    group by 1, 2
    order by 1, 2
  loop
    if line.qty is null or line.qty <= 0 then
      raise exception 'Quantity must be more than zero.';
    end if;
    if line.price < 0 then
      raise exception 'Price cannot be below zero.';
    end if;

    -- FOR UPDATE makes a second device wait here, then see the new stock
    select * into item from public.products where id = line.product_id for update;
    if not found then
      raise exception 'A product in this record was deleted. Please check and try again.';
    end if;

    change := case when p_type = 'IN' then line.qty else -line.qty end;
    if item.stock + change < 0 then
      raise exception 'Not enough %. Only % % left.', item.name, item.stock, item.unit;
    end if;

    update public.products set stock = stock + change where id = item.id;
    insert into public.movements
      (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after,
       unit_price, unit_cost, contact)
    values
      (now_here::date, to_char(now_here, 'HH24:MI'), item.id, item.name, p_type, line.qty, change,
       left(coalesce(p_note, ''), 500), item.stock + change,
       case when p_type = 'OUT' then line.price end,
       case when p_type = 'IN' then line.price end,
       who);
  end loop;

  if who <> '' then
    insert into public.contacts (kind, name)
    values (case when p_type = 'OUT' then 'customer' else 'supplier' end, who)
    on conflict (kind, lower(name)) do nothing;
  end if;
end;
$$;

-- Add a product (p_id is null) or edit one. A changed stock number is saved in
-- the history as a correction, not counted as IN or OUT.
create or replace function public.save_product(
  p_id bigint, p_name text, p_kind text, p_unit text, p_stock numeric, p_min numeric
)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  item public.products%rowtype;
  now_here timestamp := public.shop_time();
begin
  perform public.require_access(array['full']);

  if p_id is null then
    insert into public.products (name, kind, unit, stock, min_stock)
    values (p_name, p_kind, p_unit, p_stock, p_min);
    return;
  end if;

  select * into item from public.products where id = p_id for update;
  if not found then
    raise exception 'This product was deleted on another device.';
  end if;

  update public.products
  set name = p_name, kind = p_kind, unit = p_unit, stock = p_stock, min_stock = p_min
  where id = p_id;

  if p_stock <> item.stock then
    insert into public.movements
      (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after)
    values
      (now_here::date, to_char(now_here, 'HH24:MI'), p_id, p_name, 'ADJUST',
       abs(p_stock - item.stock), p_stock - item.stock, 'Manual correction', p_stock);
  end if;
end;
$$;

create or replace function public.delete_product(p_id bigint)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);
  delete from public.products where id = p_id;
end;
$$;

-- Undo one record: put the stock back and add an UNDO row to the history.
create or replace function public.undo_record(p_id bigint)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  target public.movements%rowtype;
  item public.products%rowtype;
  now_here timestamp := public.shop_time();
begin
  perform public.require_access(array['full']);

  -- FOR UPDATE makes a second device wait here, then see that it was undone
  select * into target from public.movements where id = p_id for update;
  if not found then
    raise exception 'This record was not found.';
  end if;
  if target.type = 'UNDO' then
    raise exception 'This record cannot be undone.';
  end if;
  if exists (select from public.movements where undoes_id = p_id) then
    raise exception 'This record was already undone.';
  end if;

  select * into item from public.products where id = target.product_id for update;
  if not found then
    raise exception 'A product in this record was deleted. Please check and try again.';
  end if;
  if item.stock - target.delta < 0 then
    raise exception 'Not enough %. Only % % left.', item.name, item.stock, item.unit;
  end if;

  update public.products set stock = stock - target.delta where id = item.id;
  insert into public.movements
    (move_date, move_time, product_id, product_name, type, qty, delta, stock_after, undoes_id)
  values
    (now_here::date, to_char(now_here, 'HH24:MI'), item.id, item.name, 'UNDO',
     target.qty, -target.delta, item.stock - target.delta, p_id);
end;
$$;

-- The reorder warning levels on the Insights page
create or replace function public.save_settings(p_order_now integer, p_order_soon integer)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);
  if p_order_now < 1 or p_order_soon < p_order_now then
    raise exception 'Order soon must be the same as or more than Order now.';
  end if;
  update public.app_settings set order_now_days = p_order_now, order_soon_days = p_order_soon;
end;
$$;

-- Replace ALL products and history for everyone. Used by "Delete all data",
-- "Load sample data" and "Move data from this browser".
create or replace function public.replace_all_data(p_products jsonb, p_movements jsonb)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);

  delete from public.movements where true;
  delete from public.products where true;
  delete from public.contacts where true;

  insert into public.products (id, name, kind, unit, stock, min_stock)
  select (p ->> 'id')::bigint, p ->> 'name', p ->> 'kind', p ->> 'unit',
         (p ->> 'stock')::numeric, (p ->> 'min')::numeric
  from jsonb_array_elements(p_products) as p;

  insert into public.movements
    (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after,
     unit_price, unit_cost, contact)
  select (m ->> 'date')::date, coalesce(m ->> 'time', ''), (m ->> 'productId')::bigint,
         m ->> 'productName', m ->> 'type', (m ->> 'qty')::numeric, (m ->> 'delta')::numeric,
         coalesce(m ->> 'note', ''), (m ->> 'stockAfter')::numeric,
         (m ->> 'unitPrice')::numeric, (m ->> 'unitCost')::numeric, coalesce(m ->> 'contact', '')
  from jsonb_array_elements(p_movements) with ordinality as entries (m, pos)
  order by pos;

  insert into public.contacts (kind, name)
  select case when type = 'OUT' then 'customer' else 'supplier' end, min(contact)
  from public.movements
  where contact <> '' and type in ('IN', 'OUT')
  group by type, lower(contact);

  -- New products must get an id after the ones just added
  perform setval(
    pg_get_serial_sequence('public.products', 'id'),
    coalesce((select max(id) from public.products), 1),
    exists (select from public.products)
  );
end;
$$;

