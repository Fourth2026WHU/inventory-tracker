-- Replace everything with the contents of a backup file. It keeps the ids, so
-- undone records stay linked. All of it is saved, or none of it if one row fails.
-- Older backup files have no orders or recipes.
drop function if exists public.restore_backup(jsonb, jsonb, jsonb, integer, integer);
drop function if exists public.restore_backup(jsonb, jsonb, jsonb, integer, integer, jsonb);
create or replace function public.restore_backup(
  p_products jsonb, p_movements jsonb, p_contacts jsonb, p_order_now integer, p_order_soon integer,
  p_orders jsonb default '[]'::jsonb, p_recipes jsonb default '[]'::jsonb
)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);
  if p_order_now < 1 or p_order_soon < p_order_now then
    raise exception 'Order soon must be the same as or more than Order now.';
  end if;

  delete from public.movements where true;
  delete from public.products where true;
  delete from public.contacts where true;
  delete from public.purchase_orders where true;

  insert into public.products (id, name, kind, unit, stock, min_stock, code)
  select (p ->> 'id')::bigint, p ->> 'name', p ->> 'kind', p ->> 'unit',
         (p ->> 'stock')::numeric, (p ->> 'min')::numeric, nullif(trim(p ->> 'code'), '')
  from jsonb_array_elements(p_products) as p;

  insert into public.movements
    (id, move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after,
     unit_price, unit_cost, contact, undoes_id, recorded_by, batch_id)
  select (m ->> 'id')::bigint, (m ->> 'date')::date, coalesce(m ->> 'time', ''),
         (m ->> 'productId')::bigint, m ->> 'productName', m ->> 'type', (m ->> 'qty')::numeric,
         (m ->> 'delta')::numeric, coalesce(m ->> 'note', ''), (m ->> 'stockAfter')::numeric,
         (m ->> 'unitPrice')::numeric, (m ->> 'unitCost')::numeric, coalesce(m ->> 'contact', ''),
         (m ->> 'undoesId')::bigint, coalesce(m ->> 'recordedBy', ''), (m ->> 'batchId')::bigint
  from jsonb_array_elements(p_movements) as m;

  insert into public.contacts (kind, name)
  select c ->> 'kind', c ->> 'name'
  from jsonb_array_elements(p_contacts) as c
  on conflict (kind, lower(name)) do nothing;

  insert into public.recipe_items (product_id, material_id, qty)
  select (r ->> 'productId')::bigint, (r ->> 'materialId')::bigint, (r ->> 'qty')::numeric
  from jsonb_array_elements(p_recipes) as r;

  insert into public.purchase_orders
    (id, order_date, product_id, product_name, qty, contact, status, ordered_by)
  select (o ->> 'id')::bigint, (o ->> 'date')::date, (o ->> 'productId')::bigint, o ->> 'productName',
         (o ->> 'qty')::numeric, coalesce(o ->> 'contact', ''), o ->> 'status', coalesce(o ->> 'orderedBy', '')
  from jsonb_array_elements(p_orders) as o;

  update public.app_settings set order_now_days = p_order_now, order_soon_days = p_order_soon where true;

  -- New rows must get an id after the ones just added
  perform setval(
    pg_get_serial_sequence('public.products', 'id'),
    coalesce((select max(id) from public.products), 1),
    exists (select from public.products)
  );
  perform setval(
    pg_get_serial_sequence('public.purchase_orders', 'id'),
    coalesce((select max(id) from public.purchase_orders), 1),
    exists (select from public.purchase_orders)
  );
  perform setval(
    pg_get_serial_sequence('public.movements', 'id'),
    coalesce((select max(id) from public.movements), 1),
    exists (select from public.movements)
  );
end;
$$;

-- ---------- orders from the website ----------

-- The website sends an order here. Anyone may call it without logging in,
-- so it checks every field and refuses a flood of orders.
create or replace function public.submit_web_order(
  p_name text, p_phone text, p_lines jsonb, p_company text default '', p_note text default ''
)
returns bigint
language plpgsql security definer
set search_path = ''
as $$
declare
  who text := trim(coalesce(p_name, ''));
  tel text := regexp_replace(coalesce(p_phone, ''), '[^0-9+]', '', 'g');
  clean jsonb;
  made bigint;
begin
  if length(who) not between 1 and 100 then
    raise exception 'Please fill in your name.';
  end if;
  if length(tel) not between 9 and 15 then
    raise exception 'Please check the phone number.';
  end if;
  if length(coalesce(p_company, '')) > 200 or length(coalesce(p_note, '')) > 1000 then
    raise exception 'The text is too long.';
  end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) > 60 then
    raise exception 'The product list is not valid.';
  end if;
  if jsonb_array_length(p_lines) = 0 and trim(coalesce(p_note, '')) = '' then
    raise exception 'Add a product or tell us what you need.';
  end if;
  if (select count(*) from public.web_orders where created_at > now() - interval '1 hour') >= 30
     or (select count(*) from public.web_orders
         where phone = tel and created_at > now() - interval '1 hour') >= 5 then
    raise exception 'Too many orders right now. Please send it on LINE or call us.';
  end if;

  -- Keep only the fields that are used
  select coalesce(jsonb_agg(jsonb_build_object(
           'code', upper(left(trim(l ->> 'code'), 30)), 'name', left(trim(l ->> 'name'), 200),
           'qty', (l ->> 'qty')::numeric, 'unit', left(trim(coalesce(l ->> 'unit', '')), 30))), '[]'::jsonb)
  into clean
  from jsonb_array_elements(p_lines) as l;
  if exists (select from jsonb_array_elements(clean) as l
             where coalesce(l ->> 'code', '') = '' or coalesce(l ->> 'name', '') = ''
                or coalesce((l ->> 'qty')::numeric, 0) <= 0 or (l ->> 'qty')::numeric > 10000000) then
    raise exception 'The product list is not valid.';
  end if;

  insert into public.web_orders (name, company, phone, note, lines)
  values (who, trim(coalesce(p_company, '')), tel, trim(coalesce(p_note, '')), clean)
  returning id into made;
  return made;
end;
$$;

-- Packing takes the products out of stock, found by their code.
-- p_prices is optional, the selling price by code: {"TC-N001": 12.5}
create or replace function public.pack_web_order(p_id bigint, p_prices jsonb default '{}'::jsonb)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  ord public.web_orders%rowtype;
  missing text;
  cart jsonb;
begin
  perform public.require_access(array['full', 'limited']);
  select * into ord from public.web_orders where id = p_id for update;
  if not found then
    raise exception 'This order was not found.';
  end if;
  if ord.status not in ('new', 'read') then
    raise exception 'This order was already packed or cancelled.';
  end if;
  if jsonb_array_length(ord.lines) = 0 then
    raise exception 'This order has no products to pack.';
  end if;

  select string_agg(l ->> 'code', ', ') into missing
  from jsonb_array_elements(ord.lines) as l
  where not exists (select from public.products p where upper(p.code) = upper(l ->> 'code'));
  if missing is not null then
    raise exception 'No product has the code %. Add the code to the product in Stock first.', missing;
  end if;

  select jsonb_agg(jsonb_build_object(
           'product_id', p.id, 'qty', (l ->> 'qty')::numeric,
           'price', (coalesce(p_prices, '{}'::jsonb) ->> (l ->> 'code'))::numeric))
  into cart
  from jsonb_array_elements(ord.lines) as l
  join public.products p on upper(p.code) = upper(l ->> 'code');

  perform public.record_cart('OUT', cart, 'Web order #' || ord.id,
    case when ord.company <> '' then ord.company else ord.name end);
  update public.web_orders
  set status = 'packed', packed_lines = cart, updated_at = now(), updated_by = public.current_name()
  where id = p_id;
end;
$$;

-- Mark an order as read, sent or cancelled. Cancelling a packed order
-- puts its products back in stock.
create or replace function public.set_web_order_status(p_id bigint, p_status text)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  ord public.web_orders%rowtype;
  back jsonb;
begin
  perform public.require_access(array['full', 'limited']);
  select * into ord from public.web_orders where id = p_id for update;
  if not found then
    raise exception 'This order was not found.';
  end if;

  if p_status = 'read' then
    if ord.status <> 'new' then return; end if;
  elsif p_status = 'shipped' then
    if ord.status <> 'packed' then
      raise exception 'Pack this order before marking it as sent.';
    end if;
  elsif p_status = 'cancelled' then
    if ord.status in ('shipped', 'cancelled') then
      raise exception 'This order can no longer be cancelled.';
    end if;
    if ord.status = 'packed' then
      select jsonb_agg(l - 'price') into back from jsonb_array_elements(ord.packed_lines) as l;
      perform public.record_cart('IN', back, 'Web order #' || ord.id || ' cancelled', '');
    end if;
  else
    raise exception 'Unknown order status.';
  end if;

  update public.web_orders
  set status = p_status, updated_at = now(), updated_by = public.current_name()
  where id = p_id;
end;
$$;

