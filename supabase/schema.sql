-- ---------- reading ----------

-- Today's IN and OUT totals for the Home page. Limited accounts cannot read
-- movements, so this gives them the two totals and nothing else.
create or replace function public.today_totals()
returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  perform public.require_access(array['full', 'limited']);
  select jsonb_build_object(
    'in',  coalesce(sum(qty) filter (where type = 'IN'), 0),
    'out', coalesce(sum(qty) filter (where type = 'OUT'), 0)
  ) into result
  from public.movements as m
  where m.move_date = public.shop_time()::date
    and not exists (select from public.movements as u where u.undoes_id = m.id);
  return result;
end;
$$;

-- Everything in a backup file, in the same shape the app downloads, so Settings
-- can restore it. Together with mark_backup, it is all a backup account can do.
create or replace function public.backup_data()
returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  perform public.require_access(array['backup']);
  select jsonb_build_object(
    'app', 'tc-inventory-backup',
    'version', 1,
    'createdAt', now(),
    'products', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', id, 'name', name, 'kind', kind, 'unit', unit, 'stock', stock, 'min', min_stock
      ) order by id), '[]'::jsonb)
      from public.products
    ),
    'movements', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', id, 'date', move_date, 'time', move_time, 'productId', product_id,
        'productName', product_name, 'type', type, 'qty', qty, 'delta', delta, 'note', note,
        'stockAfter', stock_after, 'unitPrice', unit_price, 'unitCost', unit_cost,
        'contact', contact, 'undoesId', undoes_id, 'recordedBy', recorded_by
      ) order by id), '[]'::jsonb)
      from public.movements
    ),
    'contacts', (
      select coalesce(jsonb_agg(jsonb_build_object('kind', kind, 'name', name) order by name), '[]'::jsonb)
      from public.contacts
    ),
    'orders', (
      select coalesce(jsonb_agg(jsonb_build_object(
        'id', id, 'date', order_date, 'productId', product_id, 'productName', product_name,
        'qty', qty, 'contact', contact, 'status', status, 'orderedBy', ordered_by
      ) order by id), '[]'::jsonb)
      from public.purchase_orders
    ),
    'settings', (
      select jsonb_build_object('now', order_now_days, 'soon', order_soon_days)
      from public.app_settings
    )
  ) into result;
  return result;
end;
$$;

-- ---------- writing ----------

-- Record stock IN or OUT for many products at once. All lines are saved
-- together, or none are if one fails.
-- p_lines looks like [{"product_id": 1, "qty": 5, "price": 120}, ...]
-- price is optional: the selling price for OUT, the cost for IN.
-- p_contact is the customer for OUT or the supplier for IN, also optional.
drop function if exists public.record_cart(text, jsonb, text);
create or replace function public.record_cart(
  p_type text, p_lines jsonb, p_note text default '', p_contact text default ''
)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  line record;
  item public.products%rowtype;
  change numeric;
  now_here timestamp := public.shop_time();
  who text := left(trim(coalesce(p_contact, '')), 200);
begin
  perform public.require_access(array['full', 'limited']);
  if p_type not in ('IN', 'OUT') then
    raise exception 'Unknown record type.';
  end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Add at least one product.';
  end if;

  -- Same order every time, so two devices saving at once cannot block each other
  for line in
    select (l ->> 'product_id')::bigint as product_id, (l ->> 'price')::numeric as price,
           sum((l ->> 'qty')::numeric) as qty
    from jsonb_array_elements(p_lines) as l
    group by 1, 2
    order by 1, 2
  loop
    if line.qty is null or line.qty <= 0 then
      raise exception 'Quantity must be more than zero.';
    end if;
    if line.price < 0 then
      raise exception 'Price cannot be below zero.';
    end if;

    -- FOR UPDATE makes a second device wait here, then see the new stock
    select * into item from public.products where id = line.product_id for update;
    if not found then
      raise exception 'A product in this record was deleted. Please check and try again.';
    end if;

    change := case when p_type = 'IN' then line.qty else -line.qty end;
    if item.stock + change < 0 then
      raise exception 'Not enough %. Only % % left.', item.name, item.stock, item.unit;
    end if;

    update public.products set stock = stock + change where id = item.id;
    insert into public.movements
      (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after,
       unit_price, unit_cost, contact, recorded_by)
    values
      (now_here::date, to_char(now_here, 'HH24:MI'), item.id, item.name, p_type, line.qty, change,
       left(coalesce(p_note, ''), 500), item.stock + change,
       case when p_type = 'OUT' then line.price end,
       case when p_type = 'IN' then line.price end,
       who, public.current_name());
  end loop;

  if who <> '' then
    insert into public.contacts (kind, name)
    values (case when p_type = 'OUT' then 'customer' else 'supplier' end, who)
    on conflict (kind, lower(name)) do nothing;
  end if;
end;
$$;

-- Add a product (p_id is null) or edit one. A changed stock number is saved in
-- the history as a correction, not counted as IN or OUT.
create or replace function public.save_product(
  p_id bigint, p_name text, p_kind text, p_unit text, p_stock numeric, p_min numeric
)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  item public.products%rowtype;
  now_here timestamp := public.shop_time();
begin
  perform public.require_access(array['full']);

  if p_id is null then
    insert into public.products (name, kind, unit, stock, min_stock)
    values (p_name, p_kind, p_unit, p_stock, p_min);
    return;
  end if;

  select * into item from public.products where id = p_id for update;
  if not found then
    raise exception 'This product was deleted on another device.';
  end if;

  update public.products
  set name = p_name, kind = p_kind, unit = p_unit, stock = p_stock, min_stock = p_min
  where id = p_id;

  if p_stock <> item.stock then
    insert into public.movements
      (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after, recorded_by)
    values
      (now_here::date, to_char(now_here, 'HH24:MI'), p_id, p_name, 'ADJUST',
       abs(p_stock - item.stock), p_stock - item.stock, 'Manual correction', p_stock, public.current_name());
  end if;
end;
$$;

-- Save a stock count. Each product becomes the number counted, and any difference
-- is saved in the history as a correction. All lines are saved, or none are.
-- p_lines looks like [{"product_id": 1, "counted": 60}, ...]
create or replace function public.record_count(p_lines jsonb)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  line record;
  item public.products%rowtype;
  now_here timestamp := public.shop_time();
begin
  perform public.require_access(array['full']);
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Add at least one product.';
  end if;

  -- Same order every time, so two devices saving at once cannot block each other
  for line in
    select (l ->> 'product_id')::bigint as product_id, (l ->> 'counted')::numeric as counted
    from jsonb_array_elements(p_lines) as l
    order by 1
  loop
    if line.counted is null or line.counted < 0 then
      raise exception 'The counted number cannot be below zero.';
    end if;

    select * into item from public.products where id = line.product_id for update;
    if not found then
      raise exception 'A product in this record was deleted. Please check and try again.';
    end if;
    continue when line.counted = item.stock;

    update public.products set stock = line.counted where id = item.id;
    insert into public.movements
      (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after, recorded_by)
    values
      (now_here::date, to_char(now_here, 'HH24:MI'), item.id, item.name, 'ADJUST',
       abs(line.counted - item.stock), line.counted - item.stock, 'Stock count', line.counted,
       public.current_name());
  end loop;
end;
$$;

-- Remember that stock was ordered, so nobody orders it again
create or replace function public.place_order(p_product_id bigint, p_qty numeric, p_contact text default '')
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  item public.products%rowtype;
  who text := left(trim(coalesce(p_contact, '')), 200);
begin
  perform public.require_access(array['full']);
  if p_qty is null or p_qty <= 0 then
    raise exception 'Quantity must be more than zero.';
  end if;

  select * into item from public.products where id = p_product_id;
  if not found then
    raise exception 'A product in this record was deleted. Please check and try again.';
  end if;

  insert into public.purchase_orders (order_date, product_id, product_name, qty, contact, ordered_by)
  values (public.shop_time()::date, item.id, item.name, p_qty, who, public.current_name());

  if who <> '' then
    insert into public.contacts (kind, name) values ('supplier', who)
    on conflict (kind, lower(name)) do nothing;
  end if;
end;
$$;

-- The stock arrived: add it as a normal stock IN. p_cost is optional.
create or replace function public.receive_order(p_id bigint, p_qty numeric, p_cost numeric default null)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  target public.purchase_orders%rowtype;
  item public.products%rowtype;
  now_here timestamp := public.shop_time();
begin
  perform public.require_access(array['full']);
  if p_qty is null or p_qty <= 0 then
    raise exception 'Quantity must be more than zero.';
  end if;
  if p_cost < 0 then
    raise exception 'Price cannot be below zero.';
  end if;

  -- FOR UPDATE makes a second device wait here, then see that it was received
  select * into target from public.purchase_orders where id = p_id for update;
  if not found or target.status <> 'open' then
    raise exception 'This order was already closed on another device.';
  end if;

  select * into item from public.products where id = target.product_id for update;
  if not found then
    raise exception 'A product in this record was deleted. Please check and try again.';
  end if;

  update public.products set stock = stock + p_qty where id = item.id;
  update public.purchase_orders set status = 'received' where id = p_id;
  insert into public.movements
    (move_date, move_time, product_id, product_name, type, qty, delta, stock_after,
     unit_cost, contact, recorded_by)
  values
    (now_here::date, to_char(now_here, 'HH24:MI'), item.id, item.name, 'IN', p_qty, p_qty,
     item.stock + p_qty, p_cost, target.contact, public.current_name());
end;
$$;

create or replace function public.cancel_order(p_id bigint)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);
  update public.purchase_orders set status = 'cancelled' where id = p_id and status = 'open';
  if not found then
    raise exception 'This order was already closed on another device.';
  end if;
end;
$$;

