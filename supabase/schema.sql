-- =====================================================
-- Inventory Tracker database
-- Paste this whole file into the Supabase SQL Editor and press Run.
-- It is safe to run again after an update: it keeps existing data.
--
-- How access works:
--   profiles   says which accounts exist and whether they are full or limited.
--              Nobody can change it from the app, only from the Supabase dashboard.
--              A backup account is for the daily backup. It cannot use the app.
--   products   any account in profiles can read it.
--   movements  only full accounts can read it.
--   Writing    no account can write to a table directly. Every change goes
--              through a function below, and each one checks the access first.
-- A login with no row in profiles can read and do nothing.
-- =====================================================

-- The shop's time zone, used to decide what date and time a record belongs to.
create or replace function public.shop_time()
returns timestamp
language sql stable
set search_path = ''
as $$ select now() at time zone 'Asia/Shanghai' $$;

-- ---------- tables ----------

create table if not exists public.profiles (
  user_id  uuid primary key references auth.users (id) on delete cascade,
  username text not null unique,
  name     text not null,
  access   text not null check (access in ('full', 'limited'))
);
alter table public.profiles drop constraint if exists profiles_access_check;
alter table public.profiles add constraint profiles_access_check
  check (access in ('full', 'limited', 'backup'));

create table if not exists public.products (
  id        bigint generated by default as identity primary key,
  name      text not null check (length(name) between 1 and 200),
  kind      text not null check (kind in ('material', 'product')),
  unit      text not null check (length(unit) between 1 and 50),
  stock     numeric not null default 0,
  min_stock numeric not null default 0
);

-- Not linked to products, because history stays after a product is deleted.
create table if not exists public.movements (
  id           bigint generated by default as identity primary key,
  move_date    date not null,
  move_time    text not null default '',
  product_id   bigint not null,
  product_name text not null,
  type         text not null check (type in ('IN', 'OUT', 'ADJUST')),
  qty          numeric not null check (qty >= 0),
  delta        numeric not null,
  note         text not null default '',
  stock_after  numeric
);

-- Prices change from sale to sale, so they are saved on each record:
-- unit_price is the selling price of an OUT, unit_cost is the cost of an IN.
-- contact is the customer of an OUT, or the supplier of an IN.
alter table public.movements add column if not exists unit_price numeric check (unit_price >= 0);
alter table public.movements add column if not exists unit_cost numeric check (unit_cost >= 0);
alter table public.movements add column if not exists contact text not null default '';

-- Nothing is deleted from the history. Undoing a record adds an UNDO row that
-- points at it through undoes_id, and each record can only be undone once.
alter table public.movements add column if not exists undoes_id bigint unique references public.movements (id);
alter table public.movements drop constraint if exists movements_type_check;
alter table public.movements add constraint movements_type_check
  check (type in ('IN', 'OUT', 'ADJUST', 'UNDO'));

-- The name of the account that made each record
alter table public.movements add column if not exists recorded_by text not null default '';

-- The names offered in the Customer and Supplier boxes on the Record page
create table if not exists public.contacts (
  id   bigint generated by default as identity primary key,
  kind text not null check (kind in ('customer', 'supplier')),
  name text not null check (length(name) between 1 and 200)
);
create unique index if not exists contacts_kind_name on public.contacts (kind, lower(name));

-- Stock that was ordered and has not arrived yet. Not linked to products, so an
-- order stays after its product is deleted and can still be cancelled.
create table if not exists public.purchase_orders (
  id           bigint generated by default as identity primary key,
  order_date   date not null,
  product_id   bigint not null,
  product_name text not null,
  qty          numeric not null check (qty > 0),
  contact      text not null default '',
  status       text not null default 'open' check (status in ('open', 'received', 'cancelled')),
  ordered_by   text not null default ''
);

-- Shared settings. There is only ever one row.
create table if not exists public.app_settings (
  id              integer primary key default 1 check (id = 1),
  order_now_days  integer not null default 14,
  order_soon_days integer not null default 21
);
insert into public.app_settings (id) values (1) on conflict (id) do nothing;
alter table public.app_settings add column if not exists last_backup_at timestamptz;

-- ---------- who is asking ----------

create or replace function public.current_access()
returns text
language sql stable security definer
set search_path = ''
as $$ select access from public.profiles where user_id = auth.uid() $$;

create or replace function public.current_name()
returns text
language sql stable security definer
set search_path = ''
as $$ select coalesce((select name from public.profiles where user_id = auth.uid()), '') $$;

create or replace function public.require_access(allowed text[])
returns void
language plpgsql stable security definer
set search_path = ''
as $$
begin
  if public.current_access() is null or not public.current_access() = any (allowed) then
    raise exception 'Your account is not allowed to do this.' using errcode = '42501';
  end if;
end;
$$;

