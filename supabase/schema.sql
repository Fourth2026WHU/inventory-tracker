-- =====================================================
-- Inventory Tracker database
-- Paste this whole file into the Supabase SQL Editor and press Run.
-- It is safe to run again after an update: it keeps existing data.
--
-- How access works:
--   profiles   says which accounts exist and whether they are full or limited.
--              Nobody can change it from the app, only from the Supabase dashboard.
--   products   any account in profiles can read it.
--   movements  only full accounts can read it.
--   Writing    no account can write to a table directly. Every change goes
--              through a function below, and each one checks the access first.
-- A login with no row in profiles can read and do nothing.
-- =====================================================

-- The shop's time zone, used to decide what date and time a record belongs to.
create or replace function public.shop_time()
returns timestamp
language sql stable
set search_path = ''
as $$ select now() at time zone 'Asia/Shanghai' $$;

-- ---------- tables ----------

create table if not exists public.profiles (
  user_id  uuid primary key references auth.users (id) on delete cascade,
  username text not null unique,
  name     text not null,
  access   text not null check (access in ('full', 'limited'))
);

create table if not exists public.products (
  id        bigint generated by default as identity primary key,
  name      text not null check (length(name) between 1 and 200),
  kind      text not null check (kind in ('material', 'product')),
  unit      text not null check (length(unit) between 1 and 50),
  stock     numeric not null default 0,
  min_stock numeric not null default 0
);

-- Not linked to products, because history stays after a product is deleted.
create table if not exists public.movements (
  id           bigint generated by default as identity primary key,
  move_date    date not null,
  move_time    text not null default '',
  product_id   bigint not null,
  product_name text not null,
  type         text not null check (type in ('IN', 'OUT', 'ADJUST')),
  qty          numeric not null check (qty >= 0),
  delta        numeric not null,
  note         text not null default '',
  stock_after  numeric
);

-- ---------- who is asking ----------

create or replace function public.current_access()
returns text
language sql stable security definer
set search_path = ''
as $$ select access from public.profiles where user_id = auth.uid() $$;

create or replace function public.require_access(allowed text[])
returns void
language plpgsql stable security definer
set search_path = ''
as $$
begin
  if public.current_access() is null or not public.current_access() = any (allowed) then
    raise exception 'Your account is not allowed to do this.' using errcode = '42501';
  end if;
end;
$$;

-- ---------- table rules ----------

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.movements enable row level security;

drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
  for select to authenticated
  using (user_id = auth.uid());

drop policy if exists "accounts read products" on public.products;
create policy "accounts read products" on public.products
  for select to authenticated
  using (public.current_access() in ('full', 'limited'));

drop policy if exists "full accounts read movements" on public.movements;
create policy "full accounts read movements" on public.movements
  for select to authenticated
  using (public.current_access() = 'full');

revoke all on public.profiles, public.products, public.movements from public, anon, authenticated;
grant select on public.profiles, public.products, public.movements to authenticated;

-- ---------- reading ----------

-- Today's IN and OUT totals for the Home page. Limited accounts cannot read
-- movements, so this gives them the two totals and nothing else.
create or replace function public.today_totals()
returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  perform public.require_access(array['full', 'limited']);
  select jsonb_build_object(
    'in',  coalesce(sum(qty) filter (where type = 'IN'), 0),
    'out', coalesce(sum(qty) filter (where type = 'OUT'), 0)
  ) into result
  from public.movements
  where move_date = public.shop_time()::date;
  return result;
end;
$$;

-- ---------- writing ----------

-- Record stock IN or OUT for many products at once. All lines are saved
-- together, or none are if one fails.
-- p_lines looks like [{"product_id": 1, "qty": 5}, ...]
create or replace function public.record_cart(p_type text, p_lines jsonb, p_note text default '')
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  line record;
  item public.products%rowtype;
  change numeric;
  now_here timestamp := public.shop_time();
begin
  perform public.require_access(array['full', 'limited']);
  if p_type not in ('IN', 'OUT') then
    raise exception 'Unknown record type.';
  end if;
  if p_lines is null or jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines) = 0 then
    raise exception 'Add at least one product.';
  end if;

  -- Same order every time, so two devices saving at once cannot block each other
  for line in
    select (l ->> 'product_id')::bigint as product_id, sum((l ->> 'qty')::numeric) as qty
    from jsonb_array_elements(p_lines) as l
    group by 1
    order by 1
  loop
    if line.qty is null or line.qty <= 0 then
      raise exception 'Quantity must be more than zero.';
    end if;

    -- FOR UPDATE makes a second device wait here, then see the new stock
    select * into item from public.products where id = line.product_id for update;
    if not found then
      raise exception 'A product in this record was deleted. Please check and try again.';
    end if;

    change := case when p_type = 'IN' then line.qty else -line.qty end;
    if item.stock + change < 0 then
      raise exception 'Not enough %. Only % % left.', item.name, item.stock, item.unit;
    end if;

    update public.products set stock = stock + change where id = item.id;
    insert into public.movements
      (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after)
    values
      (now_here::date, to_char(now_here, 'HH24:MI'), item.id, item.name, p_type, line.qty, change,
       left(coalesce(p_note, ''), 500), item.stock + change);
  end loop;
end;
$$;

-- Add a product (p_id is null) or edit one. A changed stock number is saved in
-- the history as a correction, not counted as IN or OUT.
create or replace function public.save_product(
  p_id bigint, p_name text, p_kind text, p_unit text, p_stock numeric, p_min numeric
)
returns void
language plpgsql security definer
set search_path = ''
as $$
declare
  item public.products%rowtype;
  now_here timestamp := public.shop_time();
begin
  perform public.require_access(array['full']);

  if p_id is null then
    insert into public.products (name, kind, unit, stock, min_stock)
    values (p_name, p_kind, p_unit, p_stock, p_min);
    return;
  end if;

  select * into item from public.products where id = p_id for update;
  if not found then
    raise exception 'This product was deleted on another device.';
  end if;

  update public.products
  set name = p_name, kind = p_kind, unit = p_unit, stock = p_stock, min_stock = p_min
  where id = p_id;

  if p_stock <> item.stock then
    insert into public.movements
      (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after)
    values
      (now_here::date, to_char(now_here, 'HH24:MI'), p_id, p_name, 'ADJUST',
       abs(p_stock - item.stock), p_stock - item.stock, 'Manual correction', p_stock);
  end if;
end;
$$;

create or replace function public.delete_product(p_id bigint)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);
  delete from public.products where id = p_id;
end;
$$;

-- Replace ALL products and history for everyone. Used by "Delete all data",
-- "Load sample data" and "Move data from this browser".
create or replace function public.replace_all_data(p_products jsonb, p_movements jsonb)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);

  delete from public.movements where true;
  delete from public.products where true;

  insert into public.products (id, name, kind, unit, stock, min_stock)
  select (p ->> 'id')::bigint, p ->> 'name', p ->> 'kind', p ->> 'unit',
         (p ->> 'stock')::numeric, (p ->> 'min')::numeric
  from jsonb_array_elements(p_products) as p;

  insert into public.movements
    (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after)
  select (m ->> 'date')::date, coalesce(m ->> 'time', ''), (m ->> 'productId')::bigint,
         m ->> 'productName', m ->> 'type', (m ->> 'qty')::numeric, (m ->> 'delta')::numeric,
         coalesce(m ->> 'note', ''), (m ->> 'stockAfter')::numeric
  from jsonb_array_elements(p_movements) with ordinality as entries (m, pos)
  order by pos;

  -- New products must get an id after the ones just added
  perform setval(
    pg_get_serial_sequence('public.products', 'id'),
    coalesce((select max(id) from public.products), 1),
    exists (select from public.products)
  );
end;
$$;

-- ---------- who may call the functions ----------

revoke execute on all functions in schema public from public, anon, authenticated;
grant execute on function public.current_access() to authenticated;
grant execute on function public.today_totals() to authenticated;
grant execute on function public.record_cart(text, jsonb, text) to authenticated;
grant execute on function public.save_product(bigint, text, text, text, numeric, numeric) to authenticated;
grant execute on function public.delete_product(bigint) to authenticated;
grant execute on function public.replace_all_data(jsonb, jsonb) to authenticated;
