-- Replace ALL products and history for everyone. Used by "Delete all data",
-- "Load sample data" and "Move data from this browser".
create or replace function public.replace_all_data(p_products jsonb, p_movements jsonb)
returns void
language plpgsql security definer
set search_path = ''
as $$
begin
  perform public.require_access(array['full']);

  delete from public.movements where true;
  delete from public.products where true;
  delete from public.contacts where true;
  delete from public.purchase_orders where true;

  insert into public.products (id, name, kind, unit, stock, min_stock, code)
  select (p ->> 'id')::bigint, p ->> 'name', p ->> 'kind', p ->> 'unit',
         (p ->> 'stock')::numeric, (p ->> 'min')::numeric, nullif(trim(p ->> 'code'), '')
  from jsonb_array_elements(p_products) as p;

  insert into public.movements
    (move_date, move_time, product_id, product_name, type, qty, delta, note, stock_after,
     unit_price, unit_cost, contact)
  select (m ->> 'date')::date, coalesce(m ->> 'time', ''), (m ->> 'productId')::bigint,
         m ->> 'productName', m ->> 'type', (m ->> 'qty')::numeric, (m ->> 'delta')::numeric,
         coalesce(m ->> 'note', ''), (m ->> 'stockAfter')::numeric,
         (m ->> 'unitPrice')::numeric, (m ->> 'unitCost')::numeric, coalesce(m ->> 'contact', '')
  from jsonb_array_elements(p_movements) with ordinality as entries (m, pos)
  order by pos;

  insert into public.contacts (kind, name)
  select case when type = 'OUT' then 'customer' else 'supplier' end, min(contact)
  from public.movements
  where contact <> '' and type in ('IN', 'OUT')
  group by type, lower(contact);

  -- New products must get an id after the ones just added
  perform setval(
    pg_get_serial_sequence('public.products', 'id'),
    coalesce((select max(id) from public.products), 1),
    exists (select from public.products)
  );
end;
$$;

